#!/usr/bin/env python3
"""Rewrite the catalogue block inside index.html from data/mission-index.json.

data/mission-index.json (made by tools/build_archive.py) is the single source of the
Moon and Mars catalogues; the block between "const ARCHIVE_MOON = [" and the end of
ARCHIVE_MARS in index.html is generated from it. Run after every archive rebuild:

    python3 tools/sync_index.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
index = json.loads((ROOT / "data/mission-index.json").read_text(encoding="utf-8"))
report = json.loads((ROOT / "data/build-report.json").read_text(encoding="utf-8"))
js = lambda v: json.dumps(v, ensure_ascii=False)


def row(r):
    path = r["source_url"].replace("https://azmth.space", "")
    default = f"/{r['planet']}/missions/{r['slug']}"
    c = r["coordinates"]
    extra = [path if path != default else None, r["thumb"], r["image_count"], r["nation"],
             [c["lat"], c["lon"], 1 if c["precision"] == "approximate" else 0] if c else None, r["source_checked_date"]]
    if r["planet"] == "moon":
        base = [r["slug"], r["name"], r["operator"], r["nation"], r["mission_type"], r["outcome"], r["year"], 1 if r["reached_surface"] else 0]
    else:
        base = [r["slug"], r["name"], r["operator"], r["entry_kind"], r["mission_type"], r["outcome"], r["year"], 1 if r["has_coordinates"] else 0]
    return "  [" + ", ".join(js(v) for v in base + extra) + "],"


moon = [row(r) for r in index if r["planet"] == "moon"]
mars = [row(r) for r in index if r["planet"] == "mars"]
c = report["counts"]
block = f"""// GENERATED by tools/sync_index.py from data/mission-index.json — do not edit by hand.
// Moon: [slug, name, operator, nation, type, outcome, year, reached surface (1/0), page path, thumbnail, images, nation, [lat, lon, approximate], facts checked]
const ARCHIVE_MOON = [
{chr(10).join(moon)}
];
// Mars: [slug, name, operator, AZMTH entry kind, type, outcome, year, has coordinates (1/0), page path, thumbnail, images, nation, [lat, lon, approximate], facts checked]
const ARCHIVE_MARS = [
{chr(10).join(mars)}
];
const ARCHIVE_BUILD = {js({"built": report["completed_utc"][:10], "moonPages": c["moon_pages_downloaded"], "marsPages": c["mars_pages_downloaded"], "moonJson": c["moon_json_count"], "marsJson": c["mars_json_entries_total"], "images": c["local_images_saved"], "imageFailures": c["image_download_failures"], "sourceErrors": c["source_errors"], "refs": c["references_total"]})};"""

p = ROOT / "index.html"
s = p.read_text(encoding="utf-8")
start = s.index("// GENERATED by tools/sync_index.py") if "// GENERATED by tools/sync_index.py" in s else s.rindex("\n", 0, s.rindex("\n", 0, s.index("const ARCHIVE_MOON = [")))+1
if "const ARCHIVE_BUILD" in s:
    end = s.index(";", s.index("const ARCHIVE_BUILD")) + 1
else:
    end = s.index("];", s.index("const ARCHIVE_MARS = [")) + 2
p.write_text(s[:start] + block + s[end:], encoding="utf-8")
print(f"index.html: {len(moon)} Moon rows, {len(mars)} Mars rows")
